// Monthly transaction statement for a bank that provides no statement PDFs (Oct 12 call, item H):
// a pure layout into Letter pages and a pdf-lib render, the worksheet/layout + worksheet/render pattern.
import { PageSizes, PDFDocument, StandardFonts } from '@cantoo/pdf-lib'
import { fit, wrap, type Measure, type WorksheetLine, type WorksheetPage } from '../worksheet/layout'
import { money, toWinAnsi } from '../worksheet/text'

export interface StatementTransaction {
  date: string
  name: string | null
  merchant_name: string | null
  amount: number
  pending: boolean
}

export interface TransactionStatementInput {
  accountName: string | null
  mask: string | null
  year: number
  month: number
  transactions: StatementTransaction[]
}

export const DOC_TITLE = 'Transaction statement (generated by ResSpark)'
export const HEADER_TEXT = 'Transaction statement — Not an official bank statement'
export const DISCLAIMER = 'Generated by ResSpark from the bank-provided transaction feed. Not an official bank statement.'

const LONG_MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
export const longMonth = (year: number, month: number) => `${LONG_MONTHS[month - 1]} ${year}`

const PAGE = { width: 612, height: 792, margin: 60 } as const
const RIGHT = PAGE.width - PAGE.margin
const BODY_TOP = PAGE.height - 90
const BODY_BOTTOM = 70
const HEADER_Y = PAGE.height - 45
const FOOTER_Y = 40
const SIZE = 12
const LEADING = 16
const AMOUNT_WIDTH = 100
const COL = { date: PAGE.margin, desc: PAGE.margin + 85 } as const

interface Row {
  height: number
  items: WorksheetLine[]
  keep?: number
}

const line = (text: string, x: number, size = SIZE, opts: { bold?: boolean; align?: 'left' | 'right' } = {}): WorksheetLine => ({
  text: toWinAnsi(text),
  x,
  size,
  ...opts,
})
const cells = (items: WorksheetLine[], keep?: number): Row => ({ height: LEADING, items, keep })
const spacer = (height = 10): Row => ({ height, items: [] })

const round = (n: number) => Math.round(n * 100) / 100

// Plaid sign convention: a positive amount is money out of the account, a negative one is money in.
export const signedMoney = (amount: number): string => (amount > 0 ? `-${money(amount)}` : amount < 0 ? `+${money(-amount)}` : money(0))

export function totals(transactions: StatementTransaction[]): { moneyIn: number; moneyOut: number; net: number } {
  let moneyIn = 0
  let moneyOut = 0
  for (const t of transactions) {
    if (t.amount < 0) moneyIn += -t.amount
    else moneyOut += t.amount
  }
  return { moneyIn: round(moneyIn), moneyOut: round(moneyOut), net: round(moneyIn - moneyOut) }
}

const amountRow = (label: string, value: string, bold = false): Row =>
  cells([line(label, COL.desc, SIZE, { bold }), line(value, RIGHT, SIZE, { bold, align: 'right' })])

function bodyRows(input: TransactionStatementInput, measure: Measure): Row[] {
  const sorted = [...input.transactions].sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0))
  const descWidth = RIGHT - AMOUNT_WIDTH - COL.desc
  const rows: Row[] = [
    { height: 24, items: [line(`Transaction statement — ${longMonth(input.year, input.month)}`, PAGE.margin, 16, { bold: true })] },
    cells([line(`${input.accountName ?? 'Account'}${input.mask ? ` ••${input.mask}` : ''}`, PAGE.margin)]),
    ...wrap(DISCLAIMER, RIGHT - PAGE.margin, SIZE, false, measure).map((t) => cells([line(t, PAGE.margin)])),
    spacer(),
    cells([line('Date', COL.date, SIZE, { bold: true }), line('Description', COL.desc, SIZE, { bold: true }), line('Amount', RIGHT, SIZE, { bold: true, align: 'right' })], 2 * LEADING),
  ]
  for (const t of sorted) {
    rows.push(
      cells([
        line(t.date, COL.date),
        line(fit(t.merchant_name ?? t.name ?? '—', descWidth, SIZE, measure), COL.desc),
        line(signedMoney(t.amount), RIGHT, SIZE, { align: 'right' }),
      ])
    )
  }
  const sum = totals(sorted)
  rows.push(
    spacer(),
    { ...amountRow('Money in', money(sum.moneyIn)), keep: 2 * LEADING },
    amountRow('Money out', money(sum.moneyOut)),
    amountRow('Net', `${sum.net < 0 ? '-' : ''}${money(Math.abs(sum.net))}`, true)
  )
  return rows
}

// Two passes: place rows on pages, then stamp the header and the `Page k of n` footer on every page.
function paginate(rows: Row[]): WorksheetPage[] {
  const bodies: Array<WorksheetPage['lines']> = [[]]
  let y = BODY_TOP
  for (const row of rows) {
    let page = bodies[bodies.length - 1]
    if (row.items.length === 0 && page.length === 0) continue
    if (y - row.height - (row.keep ?? 0) < BODY_BOTTOM && page.length > 0) {
      if (row.items.length === 0) continue
      bodies.push((page = []))
      y = BODY_TOP
    }
    y -= row.height
    for (const item of row.items) page.push({ ...item, y })
  }
  const n = bodies.length
  return bodies.map((body, i) => ({
    lines: [
      { ...line(HEADER_TEXT, PAGE.margin, 9, { bold: true }), y: HEADER_Y },
      ...body,
      { ...line(`${DISCLAIMER} Page ${i + 1} of ${n}`, PAGE.margin, 8), y: FOOTER_Y },
    ],
  }))
}

export function layoutTransactionStatement(input: TransactionStatementInput, measure: Measure): WorksheetPage[] {
  return paginate(bodyRows(input, measure))
}

export async function renderTransactionStatement(input: TransactionStatementInput): Promise<Uint8Array> {
  const doc = await PDFDocument.create()
  doc.setTitle(DOC_TITLE)
  doc.setProducer('ResSpark')
  const regular = await doc.embedFont(StandardFonts.Helvetica)
  const bold = await doc.embedFont(StandardFonts.HelveticaBold)
  const fontOf = (isBold: boolean | undefined) => (isBold ? bold : regular)
  const pages = layoutTransactionStatement(input, (text, size, isBold) => fontOf(isBold).widthOfTextAtSize(text, size))
  for (const p of pages) {
    const page = doc.addPage(PageSizes.Letter)
    for (const l of p.lines) {
      const font = fontOf(l.bold)
      const x = l.align === 'right' ? l.x - font.widthOfTextAtSize(l.text, l.size) : l.x
      page.drawText(l.text, { x, y: l.y, size: l.size, font })
    }
  }
  return doc.save({ objectsPerTick: Infinity })
}
